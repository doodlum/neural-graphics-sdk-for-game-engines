#!/usr/bin/env python3
# Generates aiss_cmd_trampolines.inc for aiss_layer.c from vulkan_core.h: one trampoline per command-buffer entry point
# (every PFN whose first parameter is a VkCommandBuffer), which forwards to the real command buffer currently being
# recorded for the game's command buffer (see "Command buffer split" in aiss_layer.c).
#
# usage: gen_cmd_trampolines.py <vulkan_core.h> <out.inc>
# SPDX-License-Identifier: MIT
import re
import sys

# Handled by hand in aiss_layer.c.
MANUAL = {"vkBeginCommandBuffer", "vkEndCommandBuffer", "vkResetCommandBuffer", "vkCmdFillBuffer"}
# Render-pass scope tracking (a split inside a render pass is refused).
RP_BEGIN = {"vkCmdBeginRenderPass", "vkCmdBeginRenderPass2", "vkCmdBeginRenderPass2KHR", "vkCmdBeginRendering",
            "vkCmdBeginRenderingKHR"}
RP_END = {"vkCmdEndRenderPass", "vkCmdEndRenderPass2", "vkCmdEndRenderPass2KHR", "vkCmdEndRendering",
          "vkCmdEndRenderingKHR", "vkCmdEndRendering2EXT", "vkCmdEndRendering2KHR"}

src = open(sys.argv[1]).read()
pat = re.compile(r"typedef\s+(\w+)\s+\(VKAPI_PTR \*PFN_(vk\w+)\)\(VkCommandBuffer\s+commandBuffer\s*(?:,(.*?))?\);")
seen, funcs = set(), []
for ret, name, rest in pat.findall(src):
    if name in seen or name in MANUAL:
        continue
    seen.add(name)
    params = []
    if rest and rest.strip():
        for p in rest.split(","):
            p = " ".join(p.split())
            m = re.search(r"(\w+)\s*(\[[^\]]*\])?$", p)
            params.append((p, m.group(1)))
    funcs.append((ret, name, params))

out = ["// Generated by gen_cmd_trampolines.py from vulkan_core.h (VK_HEADER_VERSION %s). Do not edit."
       % re.search(r"#define VK_HEADER_VERSION (\d+)", src).group(1), ""]
out.append("typedef struct CmdTable\n{")
for ret, name, params in funcs:
    out.append("    PFN_%s %s;" % (name, name))
out.append("} CmdTable;\n")
out.append("static void CmdTableInit(CmdTable* t, PFN_vkGetDeviceProcAddr gdpa, VkDevice device)\n{")
for ret, name, params in funcs:
    out.append('    t->%s = (PFN_%s)gdpa(device, "%s");' % (name, name, name))
out.append("}\n")
for ret, name, params in funcs:
    decl = ", ".join(["VkCommandBuffer commandBuffer"] + [p for p, _ in params])
    args = ", ".join(["Cur(commandBuffer)"] + [n for _, n in params])
    body = []
    if name in RP_BEGIN:
        body.append("    RenderPassScope(commandBuffer, true, \"%s\");" % name)
    if name in RP_END:
        body.append("    if (RenderPassScope(commandBuffer, false, \"%s\"))\n        return;  // already ended by the layer at an FSR 4 evaluate" % name)
    call = "CmdTableOf(commandBuffer)->%s(%s);" % (name, args)
    body.append("    %s%s" % ("" if ret == "void" else "return ", call))
    out.append("static %s VKAPI_CALL T_%s(%s)\n{\n%s\n}" % (ret, name, decl, "\n".join(body)))
out.append("")
out.append("// The trampoline for a command-buffer entry point, or NULL when the name is not one (or the device lacks it).")
out.append("static PFN_vkVoidFunction CmdTrampoline(const CmdTable* t, const char* name)\n{")
for ret, name, params in funcs:
    out.append('    if (!strcmp(name, "%s")) return t->%s ? (PFN_vkVoidFunction)T_%s : NULL;' % (name, name, name))
out.append("    return NULL;\n}")
out.append("static bool IsCmdEntryPoint(const char* name)\n{")
out.append("    static const char* const names[] = {")
for ret, name, params in funcs:
    out.append('        "%s",' % name)
out.append("    };")
out.append("    for (size_t i = 0; i < sizeof(names) / sizeof(names[0]); ++i)")
out.append("        if (!strcmp(name, names[i])) return true;")
out.append("    return false;\n}")
open(sys.argv[2], "w").write("\n".join(out) + "\n")
print("%d command-buffer entry points" % len(funcs))
